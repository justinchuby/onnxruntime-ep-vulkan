_CHILD = "--proof-ledger-child"


def _child_main(spec_path: str) -> int:
    import numpy as np
    import onnxruntime as ort

    spec = json.loads(pathlib.Path(spec_path).read_text(encoding="utf-8"))
    model = spec["model"]
    use_ep = spec["use_ep"]

    so = ort.SessionOptions()
    so.log_severity_level = 2
    if use_ep and spec.get("strict_ep"):
        # ORT'S OWN REFUSAL, FROM OUTSIDE OUR CODE (added 2026-08-02).
        #
        # Every evidence case is a single-form model: either this EP claims the node or the
        # case proves nothing.  Our attribution is already counter-based (`claimed_nodes`,
        # `dispatches_executed`), but both of those counters are written by the thing being
        # audited.  This option is ORT refusing to build the session at all if any node lands
        # on the default CPU EP, so a run that would have compared CPU against CPU raises at
        # session creation instead of returning a `worst_rel` that has to be distrusted.
        #
        # It is deliberately *not* set on the discovery pass: discovery runs before the hatch
        # is open, the node is declined by design, and a refusal there is the expected state
        # rather than a finding.
        so.add_session_config_entry("session.disable_cpu_ep_fallback", "1")
    if use_ep:
        ep_lib = os.environ["ONNXRUNTIME_VULKAN_EP_LIB"]
        try:
            ort.register_execution_provider_library("VulkanExecutionProvider", ep_lib)
        except Exception as exc:  # already registered in this process is fine
            if "already" not in str(exc).lower():
                raise
        provs = ["VulkanExecutionProvider", "CPUExecutionProvider"]
        if spec.get("strict_ep"):
            # ORT rejects `disable_cpu_ep_fallback` outright when the CPU EP is *also* named
            # explicitly ("Conflicting session configuration"), which is an InvalidArgument at
            # session creation and reads nothing about our EP. The strict arm therefore offers
            # this EP alone; the CPU EP remains available to ORT as the default it is refusing
            # to fall back to.
            provs = ["VulkanExecutionProvider"]
        sess = ort.InferenceSession(model, so, providers=provs)
    else:
        sess = ort.InferenceSession(model, so, providers=["CPUExecutionProvider"])

    rng = np.random.default_rng(spec.get("seed", 20260801))

    # Some ops are partial functions. Feeding `standard_normal` to Sqrt produces NaN for roughly
    # half the elements on *both* EPs, and a case whose reference output is half NaN exercises
    # the kernel on half its elements while looking like a full case. `input_domain` names the
    # constraint the case model requires; the generator applies it rather than hoping the
    # distribution happens to stay inside it.
    domain = spec.get("input_domain", "any")

    def _floats(shape):
        v = rng.standard_normal(shape)
        if domain == "positive":
            return np.abs(v) + 0.5
        if domain == "nonzero":
            return np.where(np.abs(v) < 0.25, np.copysign(0.25, v), v)
        if domain == "unit":
            # |x| <= 0.9 — inside the domain of asin/acos and strictly inside atanh's, whose
            # value diverges at |x| = 1. `tanh` of a normal is a clean way to get there without
            # clipping, which would pile mass on the two endpoints and test them twice.
            return 0.9 * np.tanh(v)
        if domain == "ge_one":
            # acosh is real only for x >= 1.
            return 1.0 + np.abs(v)
        if domain == "discrete":
            # A small integer-valued set. `Equal` on two independent normals is all-False —
            # a constant reference, which proves nothing — so the comparison ops need inputs
            # that actually collide sometimes. Six values over two operands gives roughly one
            # element in six equal, which exercises both branches.
            return rng.integers(-3, 3, shape).astype(np.float64)
        if domain == "withnan":
            # `IsNaN` on a finite tensor is all-False, which is the same vacuous case. The
            # non-finite values are deliberate here and land in the *input*; the output is
            # boolean and stays finite, so this does not trip the non-finite-reference guard.
            v = v.copy()
            flat = v.reshape(-1)
            if flat.size >= 4:
                flat[0::4] = np.nan
                flat[1::4] = np.inf
            return v
        if domain == "withinf":
            # `IsInf`'s four predicates differ only on the sign of an infinity, so the input has
            # to carry both. NaN is here too because it is the value most likely to be confused
            # with an infinity by a shader that tested `x != x` or `abs(x) > large`.
            v = v.copy()
            flat = v.reshape(-1)
            if flat.size >= 4:
                flat[0::4] = np.inf
                flat[1::4] = -np.inf
                flat[2::4] = np.nan
            return v
        if domain == "spread":
            # A wider float draw, for ops whose interesting behaviour is at magnitudes a unit
            # normal rarely reaches — `Cast` to an integer, whose truncation is a no-op on almost
            # every element of a standard normal.
            return 100.0 * v
        return v

    def _ints(shape, dtype):
        """Integer feeds, domain-aware.

        The default `[0, 2)` is right for indices and masks and wrong for bitwise ops: a
        `BitwiseAnd` fed zeros and ones exercises **one bit of thirty-two**, and a shader that
        got the other thirty-one wrong would pass. `bits` draws full width.
        """
        if domain == "bits":
            info = np.iinfo(dtype)
            return rng.integers(info.min, info.max, shape, dtype=np.int64).astype(dtype)
        if domain == "spread":
            # Wide enough that the value matters, narrow enough that every value is exactly
            # representable in f32 — the `i32 -> f32` case must not turn on the rounding mode of
            # an integer-to-float conversion, which is a different question from whether the cast
            # is wired up.
            return rng.integers(-100_000, 100_000, shape).astype(dtype)
        return rng.integers(0, 2, shape).astype(dtype)

    feeds = {}
    plan = spec.get("feed_plan") or {}
    symbolic = plan.get("symbolic_dims") or {}
    fixed = plan.get("fixed_inputs") or {}
    scale = float(plan.get("float_scale", 1.0))
    for inp in sess.get_inputs():
        shape = [
            d if isinstance(d, int) and d > 0 else symbolic.get(d, 2) if isinstance(d, str) else 2
            for d in inp.shape
        ]
        dt = inp.type
        if inp.name in fixed:
            f = fixed[inp.name]
            feeds[inp.name] = np.asarray(f["values"], dtype=np.dtype(f["dtype"])).reshape(
                f["shape"]
            )
            continue
        if "float16" in dt:
            feeds[inp.name] = (_floats(shape) * scale).astype(np.float16)
        elif "float" in dt or "double" in dt:
            feeds[inp.name] = (_floats(shape) * scale).astype(np.float32)
        elif "int64" in dt:
            feeds[inp.name] = _ints(shape, np.int64)
        elif "int32" in dt:
            feeds[inp.name] = _ints(shape, np.int32)
        elif "uint8" in dt:
            feeds[inp.name] = rng.integers(0, 4, shape).astype(np.uint8)
        elif "bool" in dt:
            feeds[inp.name] = rng.integers(0, 2, shape).astype(bool)
        else:
            feeds[inp.name] = _floats(shape).astype(np.float32)

    outs = sess.run(None, feeds)
    np.savez(spec["outputs"], **{f"o{i}": o for i, o in enumerate(outs)})
    return 0


