#!/usr/bin/env python
"""Generate `evidence/proof_ledger.jsonl` — the §8.9 proof ledger. Owner: Mouse.

DESIGN.md §8.9.2 rule 3: *the ledger is generated by the differential harness, never
hand-edited.  It is emitted by the run that obtained the evidence, carries the device(s), the
ORT build, the tolerance policy applied and the artifact or builder the case came from, and is
baked into the cdylib at build time.*  This is that generator.

WHY THREE PASSES, AND WHY THE FIRST ONE EXISTS
----------------------------------------------
The gate is a chicken-and-egg by construction: with an empty ledger nothing is claimed, so no
differential run can obtain evidence about a claimed form.  §8.9.4 answers it — *"enabling a
form in order to prove it is the intended use"* — but you cannot enable a key you have no way
to learn.  So:

  pass 1  (discover)  run with the gate armed and `ONNXRUNTIME_EP_VULKAN_CLAIM_LOG` set.  Every
                      node records its `proof_key` whether it was claimed or not.  Collect the
                      keys of nodes whose ONLY decline was `[unproven]` — those are exactly the
                      forms that a proof would unlock and nothing else is wrong with.
  pass 2  (prove)     re-run with `ONNXRUNTIME_EP_VULKAN_CLAIM_UNPROVEN` set to those keys, and
                      compare every output against a CPU-only run of the same model.
  pass 3  (record)    write one entry per key IF AND ONLY IF the comparison returned MATCH.

A DIVERGENT run writes nothing — §8.9.2 rule 4 makes a divergent model verdict *demote* every
form that participated, and the mechanical form of "demote" in a generated file is "do not
emit".  There is no code path in this tool that can write an entry for a run that did not match.

WHAT THIS TOOL DOES NOT DO
--------------------------
It does not decide tolerance policy and it does not own the model-level verdict vocabulary.
Both belong to Trinity (`tests/ops/_verdict.py`); this tool reports the comparison it made and
records the policy it applied by name.  A second verdict vocabulary would be the R10 sub-rule
violation the census exists to catch.

USAGE
    python rust/tools/gen_proof_ledger.py --model model.onnx [--model other.onnx ...]
                                          [--device 0] [--out evidence/proof_ledger.jsonl]
                                          [--append]

    --check     verify an existing ledger instead of writing one (digest + duplicate keys +
                every entry's evidence artifact still present and unchanged).
"""

