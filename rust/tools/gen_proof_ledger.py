ATTEMPTS = REPO / "evidence" / "proof_attempts.jsonl"


def _record_attempt(model_path, keys, verdict, detail, device, ort_build, tolerance, when):
    """Append every proof attempt, including the ones that prove nothing.

    A form that stays unproven after an honest attempt and a form nobody has attempted are two
    different states, and only one of them is a finding. The ledger cannot hold the difference:
    a non-MATCH line in `proof_ledger.jsonl` populates `Ledger::faults`, and a ledger with
    faults refuses every claim, not just the bad one. So the record goes beside it.

    This file grants nothing and is not baked into the binary. It exists so "we measured GQA
    and it disagreed by 16.7x" cannot decay into "GQA has no entry".
    """
    ATTEMPTS.parent.mkdir(parents=True, exist_ok=True)
    with ATTEMPTS.open("a", encoding="utf-8") as fh:
        fh.write(
            json.dumps(
                {
                    "case": model_path.name,
                    "keys": list(keys),
                    "verdict": verdict,
                    "detail": detail,
                    "device": device,
                    "ort_build": ort_build,
                    "tolerance": tolerance,
                    "attempted_at": when,
                },
                sort_keys=True,
            )
            + "\n"
        )


def _planted_control_key() -> str:
    """The key the ledger must never contain.

    Imported rather than duplicated: two copies of a constant is how the control gets disarmed
    on one side and left armed on the other.
    """
    try:
        import ledger_case_models
    except ImportError:
        return ""
    return getattr(ledger_case_models, "PLANTED_CONTROL_KEY", "")


def _domain_for(model: str) -> str:
    """The input sampling domain declared by the case model, keyed by file stem.

    Both arms must sample identically, so this is resolved once from the model path and passed
    to every child rather than being set per-arm.
    """
    try:
        import ledger_case_models
    except ImportError:
        return "any"
    return ledger_case_models.input_domain(pathlib.Path(model).stem)


def _feed_plan_for(model: str) -> dict:
    """Per-case overrides for inputs a random sampler cannot produce.

    Some forms have inputs that are not free variables: `GroupQueryAttention`'s
    `total_sequence_length` must equal past + current, and `seqlens_k` must agree with the KV
    cache extent. A random int32 there is not a harsher test, it is an invalid model — the CPU
    arm raises and the run reports ERROR(instrument) rather than a verdict.

    The plan is declared beside the case model, not here, for the same reason `input_domain`
    is: the next case would otherwise have to rediscover it in the runner.
    """
    try:
        import ledger_case_models
    except ImportError:
        return {}
    return ledger_case_models.feed_plan(pathlib.Path(model).stem)


def _run_child(
    model: str, use_ep: bool, env_extra: dict, outputs: pathlib.Path, strict_ep: bool = False
) -> None:
    with tempfile.TemporaryDirectory(dir=str(REPO / "bench" / "results")) as td:
        spec = pathlib.Path(td) / "spec.json"
        spec.write_text(
            json.dumps(
                {
                    "model": model,
                    "use_ep": use_ep,
                    "strict_ep": strict_ep,
                    "outputs": str(outputs),
                    "input_domain": _domain_for(model),
                    "feed_plan": _feed_plan_for(model),
                }
            ),
            encoding="utf-8",
        )
        env = dict(os.environ)
        env.update(env_extra)
        r = subprocess.run(
            [sys.executable, str(pathlib.Path(__file__).resolve()), _CHILD, str(spec)],
            env=env,
            capture_output=True,
            text=True,
            # The EP writes "§8.9.7" to its log sink. `text=True` alone decodes with the
            # platform default (cp1252 here), the decode raises inside subprocess's reader
            # *thread*, and the exception does not propagate — so `r.stderr` comes back empty
            # and a failing child's diagnostics are lost exactly when they are needed. R13: an
            # instrument that cannot report its own failure text turns FAIL into a mystery.
            encoding="utf-8",
            errors="replace",
            timeout=1800,
        )
        if r.returncode != 0:
            blob = f"{r.stdout}\n{r.stderr}"
            if _CPU_FALLBACK_REFUSAL in blob:
                # Not an instrument failure: ORT reached a conclusion about our EP and stated
                # it. Quote the text (R13) and let the caller record it as UNATTRIBUTED.
                raise CpuFallbackRefusal(
                    f"ORT refused the session for {model} because a node was assigned to the "
                    f"default CPU EP:\n{blob[-2000:]}"
                )
            # R13: an instrument failure is not a detection.  Raise, never return "no keys".
            raise InstrumentError(
                f"proof-ledger child failed (exit {r.returncode}) on {model}\n"
                f"--- stdout ---\n{r.stdout[-4000:]}\n--- stderr ---\n{r.stderr[-4000:]}"
            )


# ORT's own wording, observed verbatim on this build — not a string we wrote. Switch's finding of
# 2026-08-02 applies directly: *a classifier tested only against strings we wrote ourselves is
# tested against the one input it cannot get wrong*. His device-loss classifier matched
# `"device was lost"` and `"device_lost"` while the driver says `"The logical device has been
# lost"`, and fell through to the wrong class.
#
# This one is audited against that lesson and fails in the safe direction: if ORT rewords the
# message, the match misses and the run becomes `InstrumentError` — a raise, never a decline and
# never a proof. The dangerous version of this classifier would be one whose miss produced a
# verdict; this one's miss produces an error, so a reword costs a red lane, not a false entry.
_CPU_FALLBACK_REFUSAL = "fallback to CPU EP has been explicitly disabled"


class InstrumentError(RuntimeError):
    """The generator could not reach an observation.  Never a proof, never a decline."""


class CpuFallbackRefusal(RuntimeError):
    """ORT declined to build a session because a node fell to the default CPU EP.

    This is a *reading*, not an outage: it says the EP did not take the node, which for a
    single-form evidence case is exactly the vacuous-comparison state the ledger exists to
    exclude.  It is raised separately from `InstrumentError` so the two are never conflated.
    """


def discover_keys(model: str, reprove: bool = False) -> tuple[list[str], dict]:
    """Pass 1 — which forms would a proof unlock, and what else is wrong with them.

    With `reprove=True`, forms the EP **already claims** are returned as well.  Without it the
    generator can only ever measure forms that are not yet proven, which means a proven form is
    never re-measured and its entry silently outlives the kernel it describes (§8.9.11).  The
    skip is an optimisation; treating it as a policy is how a proof stops being about anything.
    """
    log = REPO / "bench" / "results" / "_ledger_claimlog.jsonl"
    if log.exists():
        log.unlink()
    outputs = REPO / "bench" / "results" / "_ledger_discover.npz"
    _run_child(model, True, {"ONNXRUNTIME_EP_VULKAN_CLAIM_LOG": str(log)}, outputs)
    if not log.is_file():
        # R13: the instrument produced no record. That is ERROR(instrument), never "no keys" —
        # "no keys" and "the claim log never opened" would otherwise be the same reading, and one
        # of them silently writes an empty ledger that certifies nothing.
        raise InstrumentError(
            f"claim log {log} was never written on {model}; the EP did not reach "
            f"claim_decision (did ORT fall back before GetCapability?)"
        )

    unlockable: list[str] = []
    census = {
        "records": 0, "unproven_only": 0, "other_decline": 0, "claimed": 0, "no_key": 0,
        "claimed_reoffered": 0,
    }
    for line in log.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        rec = json.loads(line)
        census["records"] += 1
        key = rec.get("proof_key")
        if not key:
            census["no_key"] += 1
            continue
        if rec.get("claimed"):
            census["claimed"] += 1
            if reprove and key not in unlockable:
                census["claimed_reoffered"] += 1
                unlockable.append(key)
            continue
        codes = set(rec.get("codes") or [])
        if codes == {"unproven"}:
            census["unproven_only"] += 1
            if key not in unlockable:
                unlockable.append(key)
        else:
            census["other_decline"] += 1
    return unlockable, census


def prove(model: str, keys: list[str], tolerance: tuple[float, float]) -> tuple[str, dict]:
    """Passes 2 and 3 — run both arms and compare.  Returns (verdict, detail).

    ATTRIBUTION IS PART OF THE VERDICT, NOT A NICETY.
    -------------------------------------------------
    Criterion 10 was closed on 2026-07-30 by a `MATCH` obtained from a run in which ORT had
    already fallen back to CPU — this EP executed zero nodes, so the verdict was `UNATTRIBUTED`,
    not `MATCH`, and the closure had to be withdrawn.  A ledger built the same way would be a
    file full of proofs that the CPU EP is correct.  So pass 2 also takes the EP's own counters
    and refuses to call anything MATCH unless the EP claimed nodes AND executed dispatches.
    `UNATTRIBUTED` is its own verdict and writes no entries.
    """
    import numpy as np

    if not keys:
        return "UNMEASURED", {"reason": "no unlockable keys on this model"}

    ep_out = REPO / "bench" / "results" / "_ledger_ep.npz"
    cpu_out = REPO / "bench" / "results" / "_ledger_cpu.npz"
    counters = REPO / "bench" / "results" / "_ledger_counters.json"
    if counters.exists():
        counters.unlink()
    try:
        _run_child(
            model,
            True,
            {
                "ONNXRUNTIME_EP_VULKAN_CLAIM_UNPROVEN": ";".join(keys),
                "ONNXRUNTIME_EP_VULKAN_COUNTERS_FILE": str(counters),
            },
            ep_out,
            strict_ep=True,
        )
    except CpuFallbackRefusal as exc:
        return "UNATTRIBUTED", {
            "reason": "ORT refused to build the session because a node was assigned to the "
            "default CPU EP; the comparison this run would have produced was CPU against CPU",
            "ort_refusal": str(exc)[-1200:],
            "offered": sorted(keys),
        }
    _run_child(model, False, {}, cpu_out)

    if not counters.is_file():
        raise InstrumentError(
            f"no counters file was written for {model}; attribution is unknowable, which is "
            f"ERROR(instrument) and not a verdict"
        )
    c = json.loads(counters.read_text(encoding="utf-8"))
    claimed = c.get("claimed_nodes", 0)
    dispatches = c.get("dispatches_executed", 0)
    hatch = c.get("unproven_forms_enabled", [])
    reproof = c.get("reproof_forms_admitted", [])
    admitted_keys = list(dict.fromkeys(list(hatch) + list(reproof)))
    if not claimed or not dispatches:
        return "UNATTRIBUTED", {
            "reason": "the EP claimed or executed nothing; a match against CPU proves nothing "
            "about a kernel that never ran",
            "claimed_nodes": claimed,
            "dispatches_executed": dispatches,
        }
    # ATTRIBUTION IS PER KEY, NOT PER RUN (revised 2026-08-02).
    #
    # The rule was `admitted == offered`, and it refused three legitimate proofs — `gelu_f16`,
    # `hardswish_f32`, `mish_f32`. The cause is not a defect in the EP: ORT calls `GetCapability`
    # on **more than one form of the graph** (`gelu_f16` produced 19 claim-log records for a
    # one-node model), so discovery sees keys belonging to graph states that the run that
    # actually executes does not contain. Requiring set equality made those models unprovable and
    # would have made every composite op unprovable forever.
    #
    # The replacement is stronger, not weaker, and it is stronger in the direction that matters:
    #
    #   * `admitted` must be **non-empty** — nothing used, nothing proven;
    #   * `admitted` must be a **subset** of `offered` — a key the run claimed under that nobody
    #     offered means the harness does not know what it ran, which is worse than a miss;
    #   * and the caller writes entries **only for the admitted keys**.
    #
    # Under the old rule a model offering two keys and using one wrote *two* entries whenever the
    # sets happened to match; under this one an entry can only exist for a key the run actually
    # claimed under. The number of entries a run can produce is now bounded by what it used
    # rather than by what it intended.
    if not admitted_keys:
        return "UNATTRIBUTED", {
            "reason": "the run admitted no unproven form; nothing was claimed under any offered "
            "key, so no key was exercised",
            "offered": sorted(keys),
        }
    unoffered = sorted(set(admitted_keys) - set(keys))
    if unoffered:
        return "UNATTRIBUTED", {
            "reason": "the run claimed under a key that was never offered; the harness cannot "
            "say what it ran",
            "offered": sorted(keys),
            "admitted": sorted(admitted_keys),
            "unoffered": unoffered,
        }

    a = np.load(str(ep_out))
    b = np.load(str(cpu_out))
    rtol, atol = tolerance
    worst = 0.0
    degenerate = []
    for name in a.files:
        x, y = a[name].astype("float64"), b[name].astype("float64")
        if x.shape != y.shape:
            return "DIVERGENT", {"reason": f"shape mismatch on {name}: {x.shape} vs {y.shape}"}

        # R13, and the seventh instance of this project's oldest failure mode.
        #
        # A **constant** CPU reference makes the comparison vacuous: two constant tensors agree
        # to any tolerance, so the run reports `MATCH` with `worst_rel 0.0` while having tested
        # nothing. This guard did not exist while the ledger held only arithmetic ops, whose
        # references vary by construction. It is added here because the batch that follows is
        # twelve **boolean-output** ops, where degeneracy is the default rather than the
        # accident: `Equal` on two independent normals is all-False, and so is `IsNaN`. Without
        # this, the cheapest way to "prove" twelve ops would have been to prove none of them.
        #
        # It is ERROR(instrument), not DIVERGENT: the kernel has not been shown wrong, the case
        # model has been shown inadequate. ERROR neither proves nor demotes — repair, re-run.
        if y.size > 1 and np.all(y == y.flat[0]):
            degenerate.append(name)
    if degenerate:
        return "ERROR", {
            "reason": (
                f"CPU reference output(s) {sorted(degenerate)} are constant, so the comparison "
                f"over them is vacuous: two constant tensors agree to any tolerance. The case "
                f"model does not exercise this op — repair its input domain and re-run"
            ),
            "instrument": "case_model_degenerate_reference",
        }
    for name in a.files:
        x, y = a[name].astype("float64"), b[name].astype("float64")
        if x.shape != y.shape:
            return "DIVERGENT", {"reason": f"shape mismatch on {name}: {x.shape} vs {y.shape}"}

        # R13 — an instrument error is never a detection.
        #
        # A non-finite value in the *reference* output means the case model drove the op outside
        # its domain (Sqrt of a negative, Log of a zero). Both EPs then agree on NaN, but
        # `np.allclose` reports NaN != NaN as divergence while `max(0.0, nan)` returns 0.0 — so
        # the verdict reads `DIVERGENT` with `worst_rel: 0.0`, a divergence of size zero. That
        # self-contradiction is the instrument describing itself, not the kernel. It is reported
        # as ERROR, and ERROR neither proves nor demotes: the case is repaired, then re-run.
        nonfinite_ref = int((~np.isfinite(y)).sum())
        if nonfinite_ref:
            return "ERROR", {
                "reason": (
                    f"output {name} contains {nonfinite_ref} non-finite value(s) in the CPU "
                    f"reference; the case model drove the op outside its domain, so this run "
                    f"compares NaN against NaN and can neither prove nor demote"
                ),
                "instrument": "case_model_input_domain",
            }
        nonfinite_ep = int((~np.isfinite(x)).sum())
        if nonfinite_ep:
            # Reference finite, EP non-finite: this one *is* a detection.
            return "DIVERGENT", {
                "reason": (
                    f"output {name} has {nonfinite_ep} non-finite value(s) where the CPU "
                    f"reference is finite everywhere"
                ),
            }

        denom = np.maximum(np.abs(y), 1e-30)
        rel = np.abs(x - y) / denom
        worst = max(worst, float(rel.max()) if rel.size else 0.0)
        if not np.allclose(x, y, rtol=rtol, atol=atol):
            return "DIVERGENT", {"reason": f"output {name} outside tolerance", "worst_rel": worst}
    return "MATCH", {
        "worst_rel": worst,
        "claimed_nodes": claimed,
        "dispatches_executed": dispatches,
        # §8.9.11 subject witness — which embedded SPIR-V modules this run bound, and their
        # digest, both taken from the EP's own dispatch record rather than re-derived here.
        "shaders_dispatched": c.get("shaders_dispatched", []),
        "shaders_dispatched_digest": c.get("shaders_dispatched_digest", ""),
        # §8.9.14 input witness — how many inferences this measurement is made of. One is what
        # makes the entry immune to input-cache staleness; the entry records the number so a
        # future multi-inference case cannot inherit that immunity by looking the same.
        "compute_calls": c.get("compute_calls"),
        # The keys this run actually claimed under — through the escape hatch (unproven forms) or
        # through the ledger while being deliberately re-offered (`--reprove`). Entries are
        # written for these and no others.
        "admitted": sorted(admitted_keys),
        "admitted_via_hatch": sorted(hatch),
        "admitted_via_reproof": sorted(reproof),
        # DEVICE IDENTITY, READ OFF THE RUN (added 2026-08-02, Mouse).
        #
        # `--device N` is a *selector ordinal*: a request handed to the loader, not a name for
        # hardware. Trinity's census shows `DEVICE=0` running on `1=NVIDIA`, so an entry stamped
        # `device0` names nothing a second run can be compared against. This is the name the EP
        # reports for the device it actually opened.
        "running_device_names": c.get("running_device_names", ""),
    }


