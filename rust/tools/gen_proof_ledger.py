def entry_line(key: str, device: str, ort_build: str, tolerance: str, artifact: str,
               artifact_sha256: str, generated_at: str, proof_run: dict) -> str:
    """One ledger entry, carrying the witnesses that a **proof run** produced it.

    RAI-008(a) discharge condition, provenance half.  The cheapest way to satisfy criterion 11 is
    to derive the ledger from the same enumeration that produces the claims: then
    `ledger_hits == proven_key_lookups` forever, the check can never fail, and `6/6` looks
    identical under both readings.  That is an identity whose two sides come from one source.

    The defence is not a promise in a doc comment, it is a field the claim table **cannot
    produce**.  `dispatches_executed` and `claimed_nodes` come from the EP's own execution
    counters after a session ran; `executed_by` comes from ORT's profile, an instrument this
    project does not own.  A ledger enumerated from the registry table would have to fabricate
    all three, and `registry.rs::parse_ledger` faults any entry whose attribution is absent or
    zero — so a table-derived ledger grants no claims at all rather than granting them silently.
    """
    claimed = int(proof_run.get("claimed_nodes", 0))
    dispatches = int(proof_run.get("dispatches_executed", 0))
    compute_calls = proof_run.get("compute_calls")
    shaders = sorted(proof_run.get("shaders_dispatched") or [])
    shader_digest = proof_run.get("shaders_dispatched_digest") or ""
    # THE DEVICE FIELD MUST NAME HARDWARE, NOT A REQUEST (2026-08-02, Mouse).
    #
    # `device` as passed in is `device{N}` — the *selector ordinal*, which is what the caller
    # asked the loader for and not what the loader gave it. `DEVICE=0` has run on `1=NVIDIA` in
    # this very repo. An entry stamped with an ordinal cannot be compared against a second run's
    # hardware, so `registry::device_state` classifies it `DEVICE-UNATTRIBUTED` and says so.
    #
    # The name the EP reports for the device it opened is preferred whenever the run produced
    # one. The ordinal is kept beside it, under its own key, because it is still the thing to
    # pass to reproduce the run — it is simply not an identity.
    running = (proof_run.get("running_device_names") or "").strip()
    device_selector = device
    if running and running not in ("none", "unknown"):
        device = running
    if claimed <= 0 or dispatches <= 0:
        raise SystemExit(
            f"REFUSING to write an entry for {key}: attribution is "
            f"claimed_nodes={claimed} dispatches_executed={dispatches}. An entry with no "
            f"attribution witness did not come from a proof run."
        )
    # §8.9.14 — ONE INFERENCE PER ARM, AND IT HAS TO BE A FIELD, NOT A HABIT.
    #
    # Switch found on 2026-08-02 that the input cache was keyed on `(cpu_ptr, byte_size)` with a
    # 32 KiB floor and no content check, so every inference after the first in a session read the
    # first one's inputs. It is invisible to the shader digest — the shaders did not change — so
    # it is precisely the class of staleness §8.9.11's subject witness does NOT cover.
    #
    # Every entry in this ledger is safe from it for a structural reason: each arm is a fresh
    # subprocess that builds one session and calls `sess.run` exactly once, so there is no second
    # inference for a stale cache to serve. The counters agree — `compute_calls: 1`.
    #
    # That is a true statement about today's harness and a fragile one about tomorrow's. A future
    # case that needs two inferences (a KV-cache form, say) would silently reintroduce the
    # exposure, and the entry would look identical. So the count is recorded in the entry and a
    # run that computed more than once refuses to write one until somebody has decided what a
    # multi-inference proof means.
    if compute_calls is not None and int(compute_calls) > 1:
        raise SystemExit(
            f"REFUSING to write an entry for {key}: the proof run made "
            f"{compute_calls} Compute() calls. Single-inference arms are what makes an entry "
            f"immune to input-cache staleness, which no shader digest can detect. If this case "
            f"genuinely needs several inferences, say what its proof means first."
        )
    # §8.9.11 — SUBJECT PROVENANCE.  Attribution says a run happened; it says nothing about what
    # code ran.  An entry that cannot name its shader set cannot be invalidated when that shader
    # set is replaced, and on 2026-08-02 exactly that happened: the GQA entry survived two shader
    # rewrites because `--append` skipped re-measuring an already-claimed form.  A proof that
    # cannot be invalidated by changing its subject is not a proof of that subject.
    if not shaders or not shader_digest or shader_digest == "NONE-DISPATCHED":
        raise SystemExit(
            f"REFUSING to write an entry for {key}: the run reported shaders={shaders!r} "
            f"digest={shader_digest!r}. Without a subject witness the entry would outlive the "
            f"kernel it proves. This is an instrument gap, not a licence to write the entry."
        )
    return json.dumps(
        {
            "key": key,
            "verdict": "MATCH",
            "device": device,
            "device_selector": device_selector,
            "ort_build": ort_build,
            "tolerance": tolerance,
            "artifact": artifact,
            "artifact_sha256": artifact_sha256,
            "generated_at": generated_at,
            # --- provenance: written by a proof run, never by the claim table ---
            "claimed_nodes": claimed,
            "dispatches_executed": dispatches,
            # --- subject provenance: what code this proof is about (§8.9.11) ---
            "shaders": shaders,
            "shader_digest": shader_digest,
            # --- input provenance: how many inferences this proof is made of (§8.9.14) ---
            **({} if compute_calls is None else {"compute_calls": int(compute_calls)}),
            "worst_rel": float(proof_run.get("worst_rel", 0.0)),
        },
        separators=(",", ":"),
        sort_keys=True,
    )


def write_ledger(out: pathlib.Path, lines: list[str], *, allow_shrink: bool = False) -> int:
    """Write the ledger, refusing to shrink it unless told to. Returns an R13 exit code.

    A DESTRUCTIVE WRITE THAT REPORTS SUCCESS IS THE DEFECT THIS FILE KEEPS RE-LEARNING.
    ---------------------------------------------------------------------------------
    2026-08-02, twice in one day. First: `--append` was the only path that loaded existing
    entries, so a plain run rewrote the file with what that invocation proved and then printed
    `PASS`, because `--check` was asked whether the file it had just written was internally
    consistent — which an empty file is. Fixed by always carrying entries forward. Then Switch
    hit it again through `--reprove`, 74 entries to 1, `PASS`.

    Carrying forward makes a drop *unlikely*. It does not make it a **detection**, and the
    coordinator's instruction is the right one: an entry-count drop must be `FAIL(condition)`,
    not something a reader has to notice in a line of output. So the count is compared against
    what is on disk before the write happens, and a shrink refuses to write at all.

    `allow_shrink` is `--rebuild`, which has to be asked for by name.
    """
    before = 0
    before_keys: set[str] = set()
    if out.is_file():
        try:
            existing = [
                l for l in (x.strip() for x in out.read_text(encoding="utf-8").splitlines())
                if l and not l.startswith("#")
            ]
            before = max(len(existing) - 1, 0)
            for line in existing[1:]:
                try:
                    before_keys.add(json.loads(line)["key"])
                except (ValueError, KeyError):
                    pass
        except OSError as exc:
            print(f"ERROR(instrument): cannot read {out} to compare entry counts: {exc}")
            return 3
    if before and len(lines) < before and not allow_shrink:
        keeping: set[str] = set()
        for line in lines:
            try:
                keeping.add(json.loads(line)["key"])
            except (ValueError, KeyError):
                pass
        dropped = sorted(before_keys - keeping)
        shown = "\n".join(f"    - {k}" for k in dropped[:20])
        if len(dropped) > 20:
            shown += f"\n    ... and {len(dropped) - 20} more"
        print(
            f"FAIL(condition): refusing to write {out} — it holds {before} entr(ies) and this "
            f"run would leave {len(lines)}. Entries are evidence; losing them is not a "
            f"side effect of a successful run. Nothing was written. If the shrink is intended, "
            f"say so with --rebuild.\n"
            f"  would have dropped {len(dropped)} key(s):\n{shown}"
        )
        return 1
    body = "".join(line + "\n" for line in lines)
    header = json.dumps(
        {
            "__ledger__": 1,
            "generator": "rust/tools/gen_proof_ledger.py",
            "generator_version": "1",
            "generated_at": datetime.datetime.now().astimezone().isoformat(timespec="seconds"),
            "entry_count": len(lines),
            "content_fnv1a64": f"{fnv1a64(body.encode('utf-8')):016x}",
        },
        separators=(",", ":"),
        sort_keys=True,
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header + "\n" + body, encoding="utf-8")
    return 0


def check_ledger(path: pathlib.Path) -> int:
    """The regeneration check.  PASS / FAIL(condition) / ERROR(instrument), R13."""
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        print(f"ERROR(instrument): cannot read {path}: {exc}")
        return 3
    lines = [l for l in (x.strip() for x in text.splitlines()) if l and not l.startswith("#")]
    if not lines:
        print(f"ERROR(instrument): {path} is empty — a missing ledger is not an empty one")
        return 3
    header = json.loads(lines[0])
    body = "".join(l + "\n" for l in lines[1:])
    digest = f"{fnv1a64(body.encode('utf-8')):016x}"
    failures = []
    if header.get("content_fnv1a64") != digest:
        failures.append(
            f"digest mismatch: header declares {header.get('content_fnv1a64')}, "
            f"contents hash to {digest} — the ledger has been hand-edited"
        )
    if header.get("entry_count") != len(lines) - 1:
        failures.append(
            f"entry_count {header.get('entry_count')} != {len(lines) - 1} entries present"
        )
    seen = set()
    planted = _planted_control_key()
    for raw in lines[1:]:
        e = json.loads(raw)
        key = e.get("key", "")
        if planted and key == planted:
            # The control is only a control while it is unproven. A ledger containing it looks
            # exactly like a healthy ledger, and every test that depends on the control passes
            # for the wrong reason — this is the one failure the artifact cannot self-report.
            failures.append(
                f"entry {key} is the PLANTED CONTROL key; a proof of the control disarms the "
                f"only check that shows the gate declines anything at all"
            )
        if key in seen:
            failures.append(f"duplicate key {key}")
        seen.add(key)
        if e.get("verdict") != "MATCH":
            failures.append(f"entry {key} carries verdict {e.get('verdict')!r}; only MATCH proves")
        if "/" not in key or key in {"*", "1", "all", "true", "yes"}:
            failures.append(f"key {key!r} is not a valid full proof key")
        art = e.get("artifact", "")
        art_path = REPO / art if art and not pathlib.Path(art).is_absolute() else pathlib.Path(art)
        if not art:
            failures.append(f"entry {key} names no evidence artifact")
        elif not art_path.is_file():
            failures.append(f"entry {key} names evidence {art} which does not exist")
        elif _sha256(art_path) != e.get("artifact_sha256"):
            failures.append(f"entry {key} evidence {art} has changed since it was recorded")
        # RAI-008(a): provenance. These three cannot be produced by enumerating the claim table,
        # which is the cheapest-satisfaction failure mode Morpheus named. Absent or zero is the
        # same finding as fabricated, because a run that dispatched nothing proved nothing.
        for field in ("claimed_nodes", "dispatches_executed"):
            value = e.get(field)
            if not isinstance(value, int):
                failures.append(
                    f"entry {key} carries no {field}; it does not record a proof run and may "
                    f"have been enumerated rather than proven"
                )
            elif value <= 0:
                failures.append(
                    f"entry {key} has {field}={value}; a run that claimed or dispatched nothing "
                    f"is UNATTRIBUTED and proves nothing"
                )
        # §8.9.11: subject provenance. Shape is checked here; *agreement* with the shaders in the
        # build is checked in `registry.rs::parse_ledger`, which is the only place the compiled
        # SPIR-V exists. Splitting it that way is deliberate — a Python re-derivation of the
        # digest would be a second implementation of the thing being checked.
        shaders = e.get("shaders")
        digest_field = e.get("shader_digest")
        if not isinstance(shaders, list) or not shaders:
            failures.append(
                f"entry {key} names no shader set; it cannot say what code it proved, so no "
                f"change to that code can ever invalidate it"
            )
        if not isinstance(digest_field, str) or not digest_field or digest_field == "NONE-DISPATCHED":
            failures.append(
                f"entry {key} carries no shader digest ({digest_field!r}); the entry would "
                f"outlive its subject"
            )
    if failures:
        print(f"FAIL(condition=LEDGER_INVALID): {path}")
        for f in failures:
            print(f"  - {f}")
        return 1
    print(f"PASS: {path} — {len(lines) - 1} entr(ies), digest {digest}")
    return 0


def main() -> int:
    if len(sys.argv) >= 3 and sys.argv[1] == _CHILD:
        return _child_main(sys.argv[2])

    ap = argparse.ArgumentParser()
    ap.add_argument("--model", action="append", default=[])
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--append", action="store_true")
    ap.add_argument(
        "--rebuild",
        action="store_true",
        help="DISCARD every existing entry and write only what this run proved. Without this "
        "the ledger is always carried forward: the default write used to be destructive and "
        "reported PASS over the file it had just emptied.",
    )
    ap.add_argument(
        "--reprove",
        action="store_true",
        help="re-measure forms that are ALREADY claimed and replace their entries. Without this "
             "the generator can only measure unproven forms, so an entry is never re-checked "
             "against the kernel it names and silently outlives it (§8.9.11).",
    )
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--rtol", type=float, default=1e-3)
    ap.add_argument("--atol", type=float, default=1e-5)
    ap.add_argument("--device", default=os.environ.get("ONNXRUNTIME_EP_VULKAN_DEVICE", "0"))
    ap.add_argument("--device-name", default="")
    args = ap.parse_args()

    out = pathlib.Path(args.out)
    if args.check:
        return check_ledger(out)

    if not args.model:
        ap.error("--model is required unless --check")

    os.environ["ONNXRUNTIME_EP_VULKAN_DEVICE"] = str(args.device)
    import onnxruntime as ort

    ort_build = ort.__version__
    device = args.device_name or f"device{args.device}"
    tolerance = f"rtol={args.rtol},atol={args.atol}"
    now = datetime.datetime.now().astimezone().isoformat(timespec="seconds")

    existing: list[str] = []
    if out.is_file():
        existing = [
            l for l in (x.strip() for x in out.read_text(encoding="utf-8").splitlines())
            if l and not l.startswith("#")
        ][1:]
    on_disk = {json.loads(l)["key"] for l in existing}
    # THE DEFAULT WRITE USED TO BE DESTRUCTIVE (fixed 2026-08-02, after it destroyed 95 entries).
    #
    # `existing` was loaded only under `--append`. Without it the generator rewrote the file with
    # nothing but what this invocation proved, so a single-model run reduced the ledger to that
    # model's entries — and then printed `PASS`, because `check_ledger` was asked whether the
    # file it had just written was internally consistent, which an empty file is. Two halves of a
    # report describing different things, exactly the §8.9.11 shape one level out.
    #
    # Entries are now always carried forward. Discarding them is `--rebuild`, which has to be
    # asked for, and `--append` is retained as a no-op alias so existing lanes keep working.
    if not args.append and not args.rebuild and existing:
        print(
            f"[carry]    {len(existing)} existing entr(ies) carried forward from {out.name}; "
            f"pass --rebuild to discard them deliberately"
        )
    if args.rebuild:
        print(f"[rebuild]  discarding {len(existing)} existing entr(ies) on request")
        existing = []
    have = set(on_disk) if not args.rebuild else set()

    planted = _planted_control_key()
    planted_case = getattr(
        __import__("ledger_case_models"), "PLANTED_CONTROL_CASE", "?"
    ) if planted else "?"

    new_lines = list(existing)
    measured_any = False
    reproved: list[str] = []
    for model in args.model:
        model_path = pathlib.Path(model).resolve()
        keys, census = discover_keys(str(model_path), reprove=args.reprove)
        print(f"[discover] {model_path.name}: {census}, {len(keys)} unlockable key(s)")
        for k in keys:
            print(f"    would decline without a proof: {k}")
        verdict, detail = prove(str(model_path), keys, (args.rtol, args.atol))
        print(f"[prove]    {model_path.name}: {verdict} {detail}")
        _record_attempt(model_path, keys, verdict, detail, device, ort_build, tolerance, now)
        if keys:
            measured_any = True
        else:
            # R13, and the same defect Scribe had in her health report: a run that measured
            # nothing must not contribute to a PASS. `--append` skips already-claimed forms, so
            # `UNMEASURED ... no unlockable keys` followed by `PASS` is a report whose two halves
            # describe different things — one of them the ledger's validity, the other a run that
            # did not happen.
            print(
                f"    NOT MEASURED: {model_path.name} offered no key to prove. If the form is "
                f"already claimed, this run re-checked nothing — use --reprove to re-measure it."
            )
        if verdict != "MATCH":
            print(f"    no entries written for {model_path.name} — only MATCH proves")
            continue
        sha = _sha256(model_path)
        try:
            rel = str(model_path.relative_to(REPO)).replace("\\", "/")
        except ValueError:
            rel = str(model_path).replace("\\", "/")
        # Only the admitted keys. A key that was discovered but never claimed under in the
        # proof run has no proof, however green the run looked.
        admitted = set(detail.get("admitted") or [])
        skipped = [k for k in keys if k not in admitted]
        if skipped:
            print(f"    discovered but not exercised by the proof run, so unproven: {skipped}")
        for k in keys:
            if k not in admitted:
                continue
            if k == planted:
                # 2026-08-02: the ledger acquired the planted control's form and disarmed the
                # only check that would have noticed. The generator refuses rather than warns —
                # a warning here is a line of output in a forty-minute run.
                raise SystemExit(
                    f"REFUSING to write an entry for the planted control key {k!r} "
                    f"(case {planted_case!r}). A proof of the control is the control switched "
                    f"off, and it is switched off silently. If this form genuinely needs to be "
                    f"claimable, MOVE the control first and say so, in "
                    f"rust/tools/ledger_case_models.py."
                )
            if k in have:
                if not args.reprove:
                    continue
                # Replace rather than append: two entries for one key is the fork R7 forbids, and
                # `parse_ledger` faults a duplicate. The new measurement wins because it is the
                # one taken against the shaders in this build.
                new_lines = [ln for ln in new_lines if json.loads(ln)["key"] != k]
                reproved.append(k)
            have.add(k)
            new_lines.append(
                entry_line(k, device, ort_build, tolerance, rel, sha, now, detail)
            )

    if reproved:
        print(f"[reprove]  replaced {len(reproved)} entr(ies) with fresh measurements")
    rc_write = write_ledger(out, new_lines, allow_shrink=args.rebuild)
    if rc_write != 0:
        # R13: the refusal is the terminal state. Do not run `--check` afterwards — it would be
        # asked about the file on disk, which is now the *old* one, and would answer `PASS`.
        # A report whose two halves describe different things is the defect, not the format.
        return rc_write
    print(f"[write]    {out}: {len(new_lines)} entr(ies)")
    rc = check_ledger(out)
    if rc == 0 and not measured_any:
        # The ledger is valid AND this run measured nothing. Both are true, and reporting only
        # the first is how `PASS` came to sit under `UNMEASURED`.
        print(
            "NOTE: the ledger is valid, but this run measured no form. That is a statement "
            "about the file, not about any kernel. Re-run with --reprove to measure."
        )
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
