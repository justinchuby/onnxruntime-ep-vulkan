// The external-resource-importer seam (zero-copy IO binding). NOT implemented in M0.
//
// # What it is
//
// An OS-handle-based external memory import path, added in ORT **1.24**. The caller allocates
// `VkDeviceMemory` *with `VkExportMemoryAllocateInfo`* (this must be decided up front — memory
// not allocated as exportable can never be imported), exports it to an OS handle with
// `vkGetMemoryWin32HandleKHR` (Windows) or `vkGetMemoryFdKHR` (Linux), and hands that handle to
// ORT. The EP re-imports it into its own `VkDeviceMemory` and wraps it as a zero-copy ORT tensor.
// Timeline-semaphore import for GPU↔GPU synchronisation rides along the same interface.
//
// # The symbols, precisely
//
// * EP side, ours to implement: `OrtEpFactory::CreateExternalResourceImporterForDevice`
//   (`\since Version 1.24`), returning an `OrtExternalResourceImporterImpl*`.
// * Caller side: `OrtInteropApi::CreateExternalResourceImporterForDevice`.
// * `CreateExternalResourceImporterForDeviceImpl` is **not** public API — it appears only as a
//   local static in ORT's example/test code. Do not go looking for it.
//
// The `OrtExternalResourceImporterImpl` vtable we would fill: `CanImportMemory`, `ImportMemory`,
// `ReleaseExternalMemoryHandle`, `CreateTensorFromMemory`, `CanImportSemaphore`,
// `ImportSemaphore`, `ReleaseExternalSemaphoreHandle`, `WaitSemaphore`, `SignalSemaphore`,
// `Release`. `OrtExternalMemoryHandle` and `OrtExternalSemaphoreHandle` are base structs the EP
// derives from by embedding them as the first field, the same `#[repr(C)]` trick used throughout
// this crate.
//
// # Reference implementation
//
// `onnxruntime/test/providers/nv_tensorrt_rtx/nv_vulkan_test.cc` in the ORT tree — the NV
// TensorRT RTX EP doing exactly our case, Vulkan on both sides. Match its contract rather than
// inventing our own; this is Vulkan-specific ORT support that already exists upstream.
//
// # Why it is not implemented now
//
// M0 runs everything on CPU with host-memory I/O. There is no device tensor to hand back yet, so
// an importer would have nothing to import into. The slot is left `None`, which ORT reads as
// "this EP cannot import external memory" — a legal, well-defined answer.
//
// # Why adding it later is additive, not a refactor
//
// One new `importer.rs` implementing the vtable, plus one gated line in `factory.rs`:
//
//     if negotiated.supports(sys::since::EXTERNAL_RESOURCE_IMPORTER) {
//         base.CreateExternalResourceImporterForDevice = Some(create_external_resource_importer);
//     }
//
// The gate is already meaningful: our minimum supported host is 1.24 and the API landed in 1.24,
// so it is exactly on the boundary. Nothing else in the crate moves — which is the point of
// keeping the whole ABI behind this module.
//
// # It does NOT answer OQ-3
//
// Evaluated and rejected as orthogonal; recorded in `.squad/decisions/inbox/tank-m0-foundation.md`
// so it does not get re-litigated. The importer answers "how does an external caller hand us
// *their* Vulkan buffer as a graph input or output" — and it is the complete answer to that.
// OQ-3 asks what our own `Alloc()` returns to ORT, whose allocator API is pointer-based, when a
// Vulkan allocation is a `VkBuffer` + offset. Different direction, different memory, different
// owner. That remains opaque-handle-registry vs `VK_KHR_buffer_device_address`, Tank to propose
// and Morpheus to decide.
// -------------------------------------------------------------------------------------------

/// Compile-time proof that the importer seam is present and correctly shaped in the bindings.
///
/// This is not decoration. The whole M0 claim about the importer is "the types are bound, the slot
/// exists, adding the implementation is additive" — if an ORT re-vendor renamed or removed any of
/// this, that claim would quietly stop being true and nobody would notice until someone tried to
/// implement it. Naming the items here turns that into a build failure at the moment of the bump.
///
/// It also pins the two Vulkan-specific handle-type enums, which are the values a future
/// `CanImportMemory` must accept: `VK_MEMORY_WIN32` on Windows, `VK_MEMORY_OPAQUE_FD` on Linux.
#[allow(dead_code)]
mod importer_seam {
    use super::ort;

    /// The EP-side vtable, ours to implement (see the TODO block above).
    pub type ImporterImpl = ort::OrtExternalResourceImporterImpl;
    /// The base struct an EP derives from for an imported memory handle.
    pub type MemoryHandle = ort::OrtExternalMemoryHandle;
    /// The base struct an EP derives from for an imported semaphore handle.
    pub type SemaphoreHandle = ort::OrtExternalSemaphoreHandle;
    /// Caller-side API, for reference — we never call this, applications do.
    pub type InteropApi = ort::OrtInteropApi;

    /// `vkGetMemoryWin32HandleKHR` handles.
    pub const HANDLE_TYPE_VK_MEMORY_WIN32: ort::OrtExternalMemoryHandleType =
        ort::OrtExternalMemoryHandleType_ORT_EXTERNAL_MEMORY_HANDLE_TYPE_VK_MEMORY_WIN32;
    /// `vkGetMemoryFdKHR` handles.
    pub const HANDLE_TYPE_VK_MEMORY_OPAQUE_FD: ort::OrtExternalMemoryHandleType =
        ort::OrtExternalMemoryHandleType_ORT_EXTERNAL_MEMORY_HANDLE_TYPE_VK_MEMORY_OPAQUE_FD;

    /// Timeline semaphores exported on Windows.
    pub const SEMAPHORE_TYPE_VK_TIMELINE_WIN32: ort::OrtExternalSemaphoreType =
        ort::OrtExternalSemaphoreType_ORT_EXTERNAL_SEMAPHORE_VK_TIMELINE_SEMAPHORE_WIN32;
    /// Timeline semaphores exported as an fd.
    pub const SEMAPHORE_TYPE_VK_TIMELINE_OPAQUE_FD: ort::OrtExternalSemaphoreType =
        ort::OrtExternalSemaphoreType_ORT_EXTERNAL_SEMAPHORE_VK_TIMELINE_SEMAPHORE_OPAQUE_FD;

    /// The Vulkan handle type this platform would export with.
    #[must_use]
    pub const fn native_vk_handle_type() -> ort::OrtExternalMemoryHandleType {
        if cfg!(windows) {
            HANDLE_TYPE_VK_MEMORY_WIN32
        } else {
            HANDLE_TYPE_VK_MEMORY_OPAQUE_FD
        }
    }
}

