#[cfg(test)]
mod tests {
    use super::*;

    /// A `NegotiatedApi` with dangling pointers, for testing the pure version logic only.
    fn at_version(version: u32) -> NegotiatedApi {
        NegotiatedApi {
            api: std::ptr::null(),
            ep_api: std::ptr::null(),
            version,
        }
    }

    #[test]
    fn version_window_is_well_formed() {
        assert_eq!(ORT_API_VERSION_EXPECTED, 28, "we compile and ship against ORT 1.28");
        assert_eq!(ORT_API_VERSION_MIN, 24, "declared minimum supported host is ORT 1.24");
        // The ordering invariant is asserted at compile time at module scope; see the
        // `const _: () = assert!(ORT_API_VERSION_MIN <= ORT_API_VERSION_EXPECTED)` above.
        assert_eq!(ort::ORT_API_VERSION, ORT_API_VERSION_EXPECTED);
    }

    #[test]
    fn supports_is_a_real_gate_not_a_rubber_stamp() {
        // The point of the gate is that it says *no* to a downlevel host. A `supports` that only
        // ever returns true would pass every other test in this file.
        assert!(!at_version(23).supports(since::EXTERNAL_RESOURCE_IMPORTER));
        assert!(at_version(24).supports(since::EXTERNAL_RESOURCE_IMPORTER));
        assert!(at_version(28).supports(since::EXTERNAL_RESOURCE_IMPORTER));
    }

    #[test]
    fn every_since_constant_is_inside_the_supported_window() {
        // A `since::*` below the floor is dead weight (always true, so the gate is theatre); one
        // above what we compile against cannot be reached at all.
        for &(name, v) in since::ALL {
            assert!(
                v >= ORT_API_VERSION_MIN,
                "since::{name} = {v} is below the supported floor; the gate can never fail"
            );
            assert!(
                v <= ORT_API_VERSION_EXPECTED,
                "since::{name} = {v} is newer than the ABI we compile against"
            );
        }
    }

    #[test]
    fn external_resource_importer_landed_in_1_24() {
        // Verified against ORT's own `ort_version_supported < 24` guard in
        // `ep_factory_provider_bridge.h`. Justin's brief said 1.28; it is 1.24.
        assert_eq!(since::EXTERNAL_RESOURCE_IMPORTER, 24);
    }

    #[test]
    fn importer_seam_binds_the_vulkan_handle_types() {
        // Guards the M0 claim that the seam is bound and correctly shaped, so that adding the
        // implementation later is additive. If an ORT bump renames these, this fails.
        assert_ne!(
            importer_seam::HANDLE_TYPE_VK_MEMORY_WIN32,
            importer_seam::HANDLE_TYPE_VK_MEMORY_OPAQUE_FD
        );
        assert_ne!(
            importer_seam::SEMAPHORE_TYPE_VK_TIMELINE_WIN32,
            importer_seam::SEMAPHORE_TYPE_VK_TIMELINE_OPAQUE_FD
        );
        let native = importer_seam::native_vk_handle_type();
        if cfg!(windows) {
            assert_eq!(native, importer_seam::HANDLE_TYPE_VK_MEMORY_WIN32);
        } else {
            assert_eq!(native, importer_seam::HANDLE_TYPE_VK_MEMORY_OPAQUE_FD);
        }
    }

    #[test]
    fn null_api_base_is_rejected_without_dereferencing_it() {
        // SAFETY: passing null is exactly the case under test; the function null-checks first.
        let err = unsafe { check_api_version(std::ptr::null()) }.unwrap_err();
        assert!(err.contains("null OrtApiBase"), "{err}");
    }

    #[test]
    fn make_status_with_a_null_api_returns_null_rather_than_faulting() {
        // SAFETY: null is an explicitly supported argument.
        let s = unsafe { make_status(std::ptr::null(), ort::OrtErrorCode_ORT_EP_FAIL, "boom") };
        assert!(s.is_null());
    }

    #[test]
    fn releasing_a_status_with_null_arguments_is_a_noop() {
        // SAFETY: both null arguments are explicitly supported and short-circuit.
        unsafe { release_status(std::ptr::null(), std::ptr::null_mut()) };
    }
}
